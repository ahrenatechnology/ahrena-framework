#!/usr/bin/env python3
"""Tests for check-test-placement.py.

A detector that never accepts is as broken as one that never rejects, so the
condition is pinned by failing fixtures and by the carve-outs it must not flag.
Each case builds a throwaway module, runs the hook against it as a subprocess,
and asserts on the exit code and the message.

The carve-outs are where the work is: a file that declares only types,
constants or variables owes no test; a main.go that holds only main and init
owes none; a file named for a build constraint is answered by the test of its
stem; a test file, a generated file and testdata are not held.

#288/AC-3: condition 1 of test-placement.md, the one this hook decides, has a
failing case below and the carve-outs beside it.

Usage:
    python3 engineering/go/hooks/test-check-test-placement.py
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

HOOK = Path(__file__).resolve().parent / "check-test-placement.py"

GO_MOD = "module example.com/m\n\ngo 1.23\n"

FUNCTIONS = '''package orders

func Cancel(id string) error { return nil }

func Ship(id string) error { return nil }

func archive(id string) {}
'''

METHOD_ONLY = '''package orders

type Store struct{}

func (s *Store) Get(id string) error { return nil }
'''

DECLARATIONS_ONLY = '''package orders

type ID string

const Max = 10

var Default = ID("x")

type Repo interface {
	Get(id ID) error
}
'''

MAIN_ONLY = '''package main

func init() {}

func main() {}
'''

MAIN_WITH_LOGIC = '''package main

func main() { _ = run() }

func run() error { return nil }
'''

GENERATED = '''// Code generated by stringer. DO NOT EDIT.

package orders

func (s State) String() string { return "" }
'''

TEST = "package orders\n"


def tree(files: dict[str, str]) -> dict[str, str]:
    return {"go.mod": GO_MOD, **files}



FUNC_TYPES_ONLY = '''package middleware

type Handler func(int)

type Middleware func(Handler) func(int)
'''


Case = tuple[str, dict[str, str], list[str], bool]


def case(name: str, files: dict[str, str], expect: list[str], ok: bool = False) -> Case:
    return (name, files, expect, ok)


CASES = [
    case(
        "a file of func types declares no function",
        tree({"middleware/types.go": FUNC_TYPES_ONLY}),
        ["1 file(s), no failures"],
        ok=True,
    ),
    case(
        "every GOARCH the go command knows is a constraint suffix",
        tree({"add/add_ppc.go": FUNCTIONS, "add/add_mips64p32le.go": FUNCTIONS, "add/add_test.go": TEST}),
        ["3 file(s), no failures"],
        ok=True,
    ),
    case(
        "a file of functions with no test beside it fails",
        tree({"orders/orders.go": FUNCTIONS}),
        ["[test-placement] condition 1", "orders.go declares Cancel and 2 more and has no orders_test.go beside it", "orders/orders.go:1"],
    ),
    case(
        "a file with only a method fails",
        tree({"orders/store.go": METHOD_ONLY}),
        ["[test-placement] condition 1", "store.go declares Get"],
    ),
    case(
        "the test beside it passes",
        tree({"orders/orders.go": FUNCTIONS, "orders/orders_test.go": TEST}),
        ["2 file(s), no failures"],
        ok=True,
    ),
    case(
        "a test in another directory does not answer",
        tree({"orders/orders.go": FUNCTIONS, "tests/orders_test.go": TEST}),
        ["[test-placement] condition 1"],
    ),
    case(
        "a file of declarations only owes no test",
        tree({"orders/types.go": DECLARATIONS_ONLY}),
        ["1 file(s), no failures"],
        ok=True,
    ),
    case(
        "a main.go with only main and init owes no test",
        tree({"cmd/app/main.go": MAIN_ONLY}),
        ["1 file(s), no failures"],
        ok=True,
    ),
    case(
        "a main.go with logic beside main owes one",
        tree({"cmd/app/main.go": MAIN_WITH_LOGIC}),
        ["[test-placement] condition 1", "main.go declares run"],
    ),
    case(
        "a build-constrained file is answered by its stem's test",
        tree(
            {
                "orders/orders_linux.go": FUNCTIONS,
                "orders/orders_linux_amd64.go": FUNCTIONS,
                "orders/orders_test.go": TEST,
            }
        ),
        ["3 file(s), no failures"],
        ok=True,
    ),
    case(
        "a generated file and testdata are not held",
        tree({"orders/state_string.go": GENERATED, "orders/testdata/sample.go": FUNCTIONS}),
        ["0 file(s), no failures"],
        ok=True,
    ),
]


def write(root: Path, files: dict[str, str]) -> None:
    for relative, text in files.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def run(files: dict[str, str]) -> tuple[int, str]:
    with tempfile.TemporaryDirectory() as tmp:
        write(Path(tmp), files)
        result = subprocess.run([sys.executable, str(HOOK), "."], cwd=tmp, capture_output=True, text=True)
        return result.returncode, result.stdout + result.stderr


def problems_for(expect: list[str], ok: bool, code: int, output: str) -> list[str]:
    """What went wrong with this case, or nothing."""
    wanted = "pass" if ok else "fail"
    found = [] if ok == (code == 0) else [f"expected the hook to {wanted}, it did the other"]
    found.extend(f"expected {fragment!r} in the output" for fragment in expect if fragment not in output)
    return found


def report_failure(name: str, problems: list[str], output: str) -> None:
    print(f"FAIL  {name}")
    for problem in problems:
        print(f"        {problem}")
    print("      --- hook output ---")
    for line in output.splitlines():
        print(f"      {line}")


def summarise(failed: int, total: int) -> int:
    print()
    if failed:
        print(f"{failed} of {total} cases failed.")
        return 1
    print(f"{total} cases passed.")
    return 0


def main() -> int:
    failed = 0
    for name, files, expect, ok in CASES:
        code, output = run(files)
        problems = problems_for(expect, ok, code, output)
        if problems:
            failed += 1
            report_failure(name, problems, output)
        else:
            print(f"ok    {name}")
    return summarise(failed, len(CASES))


if __name__ == "__main__":
    sys.exit(main())
